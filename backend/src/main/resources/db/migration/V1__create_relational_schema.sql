CREATE TABLE trilha (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL
);

CREATE TABLE pais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL
);

CREATE TABLE professor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL
);

CREATE TABLE aluno (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    matricula VARCHAR(255) NOT NULL UNIQUE,
    turma VARCHAR(255) NOT NULL,
    trilha_id BIGINT REFERENCES trilha (id),
    pontos INTEGER DEFAULT 0,
    senha VARCHAR(255) NOT NULL,
    pais_id BIGINT NOT NULL REFERENCES pais (id)
);

CREATE TABLE evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    descricao VARCHAR(255),
    data DATE,
    professor_id BIGINT NOT NULL REFERENCES professor (id)
);

CREATE TABLE ocorrencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(255) NOT NULL,
    data DATE,
    aluno_id BIGINT NOT NULL REFERENCES aluno (id),
    professor_id BIGINT NOT NULL REFERENCES professor (id)
);

CREATE INDEX idx_aluno_trilha_id ON aluno (trilha_id);
CREATE INDEX idx_aluno_pais_id ON aluno (pais_id);
CREATE INDEX idx_evento_professor_id ON evento (professor_id);
CREATE INDEX idx_ocorrencia_aluno_id ON ocorrencia (aluno_id);
CREATE INDEX idx_ocorrencia_professor_id ON ocorrencia (professor_id);
