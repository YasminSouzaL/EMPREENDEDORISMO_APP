CREATE TABLE escola (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL
);

INSERT INTO escola (nome)
VALUES ('Escola de demonstração');

ALTER TABLE aluno
    ADD COLUMN escola_id BIGINT REFERENCES escola (id);

ALTER TABLE professor
    ADD COLUMN escola_id BIGINT REFERENCES escola (id);

UPDATE aluno
SET escola_id = (SELECT id FROM escola WHERE nome = 'Escola de demonstração')
WHERE matricula LIKE 'DEMO-%' OR email = 'aluno@ufv.br';

UPDATE professor
SET escola_id = (SELECT id FROM escola WHERE nome = 'Escola de demonstração')
WHERE email = 'professor@ufv.br';

CREATE INDEX idx_aluno_escola_id ON aluno (escola_id);
CREATE INDEX idx_professor_escola_id ON professor (escola_id);
